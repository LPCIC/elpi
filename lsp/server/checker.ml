(* Checking a document with the Elpi compiler in error resilient mode *)

open Elpi.API

type severity = Error | Warning | Information

type diagnostic = {
  start : int;   (* byte offsets in the document *)
  stop : int;
  severity : severity;
  message : string;
}

(* the information on a unit of the program (the accumulated files, then the
   document), computed by the compiler when first asked: the types of the
   terms, the symbols with their declaration and their occurrences, the type
   expressions *)
type unit_info = LSP.info LSP.IntervalTree.t Lazy.t

type hover = unit_info list

type result = {
  diagnostics : diagnostic list;
  hover : hover option; (* unless the parser failed (the text can have errors) *)
}

let log fmt = Printf.ksprintf (fun s -> prerr_endline ("[elpi-lsp] " ^ s)) fmt

(* --- Elpi instance -------------------------------------------------------- *)

(* The errors of Elpi are the exception Error.ElpiError (the builtins too,
   see Builtin.set_runtime_error); the parser and the passes of the compiler
   return their warnings, the ones at run time are collected by Runner *)
let () = Setup.set_std_formatter Format.err_formatter

(* accumulated files are resolved relative to the accumulating file (the
   parser passes its directory as ~cwd); TJPATH is not used (only the REPL
   honours it) *)
let resolver = Parse.std_resolver ~paths:[] ()


(* --- the files of the standard library ------------------------------------- *)

(* The builtins and the standard library are not in files that the server can
   read, but the text can be generated by Elpi.
   Each transport shows these files
   to the editor in its own way (written on the disk, or served by the
   server). They depend on the builtins: each instance of Elpi has its own,
   computed the first time they are needed (see below). *)
let compute_library_files builtins =
  let b = Buffer.create 100_000 in
  let fmt = Format.formatter_of_buffer b in
  BuiltIn.document_fmt fmt builtins;
  Format.pp_print_flush fmt ();
  let files = Hashtbl.create 7 in
  let current = ref "builtin.elpi" and text = Buffer.create 100_000 in
  let flush () =
    Hashtbl.replace files !current
      ((Option.value ~default:"" (Hashtbl.find_opt files !current)) ^ Buffer.contents text);
    Buffer.clear text in
  (* #line N "file" gives the file *)
  let directive line =
    if String.length line > 6 && String.equal (String.sub line 0 6) "#line " then
      match String.split_on_char '"' line with
      | [ _; file; "" ] -> Some file
      | _ -> None
    else None in
  List.iter (fun line ->
      match directive line with
      | Some file -> flush (); current := Filename.basename file
      | None -> Buffer.add_string text line; Buffer.add_char text '\n')
    (String.split_on_char '\n' (Buffer.contents b));
  flush ();
  files

(* A cache of compiled units, one per instance of Elpi (a unit extends a
   program of its instance). A program is a list of units (the accumulated
   files, then the document), each compiled on top of the previous ones. A
   unit is identified by its digest, those of the units before it and the
   flags of the compilation: if none changed, its compilation (the program
   extended with it, its errors and warnings) is reused. So an accumulated
   file is compiled once, not at each check. Its hover information is
   computed when first asked. *)
type cached_unit = {
  extended : Compile.program;
  errors : Error.t list;
  warnings : Error.warning list;
  info : unit_info;
}

(* The cache is bounded, the least recently used unit is evicted: each edit
   of a document makes a new key for its unit (and for the units after it),
   and an entry holds a whole program. [cache_size] units are enough for the
   accumulated files of a document, and a few versions of them. *)
type cache = { units : (Digest.t, cached_unit * int ref) Hashtbl.t; mutable clock : int }

let cache_size = 64

let cache_find cache key =
  match Hashtbl.find_opt cache.units key with
  | None -> None
  | Some (c, last_use) -> cache.clock <- cache.clock + 1; last_use := cache.clock; Some c

let cache_add cache key c =
  if Hashtbl.length cache.units >= cache_size then begin
    let oldest = Hashtbl.fold (fun k (_, t) acc ->
        match acc with Some (_, t') when t' <= !t -> acc | _ -> Some (k, !t)) cache.units None in
    Option.iter (fun (k, _) -> Hashtbl.remove cache.units k) oldest
  end;
  cache.clock <- cache.clock + 1;
  Hashtbl.replace cache.units key (c, ref cache.clock)

(* An instance of Elpi, for a document: each document has its own, since the
   builtins can differ; with its library and its cache of compiled units. The
   id names it, e.g. in the URIs of the files of its library (see
   Server.library_uri). *)
type instance = { id : int; elpi : Setup.elpi; library : (string, string) Hashtbl.t Lazy.t; cache : cache }

let new_instance =
  let next = ref 0 in
  fun () ->
    incr next;
    let builtins = Elpi.Builtin.std_builtins in
    { id = !next;
      elpi = Setup.init ~builtins:[builtins] ~file_resolver:resolver ();
      library = lazy (compute_library_files builtins);
      cache = { units = Hashtbl.create 17; clock = 0 } }

let id { id } = id

let elpi { elpi } = elpi

let library_files { library } = Lazy.force library

(* the text of the file of the library [name] (eg builtin_stdlib.elpi) *)
let library_text instance name = Hashtbl.find_opt (library_files instance) (Filename.basename name)

(* whether [path] is a file of the library, opened by the editor: it is not
   meant to be edited, nor checked for determinacy. Each transport shows the
   library files to the editor in its own way, and sets it. *)
let is_library_path : (string -> bool) ref = ref (fun _ -> false)

(* --- diagnostics ------------------------------------------------------------ *)

let one_line s = String.concat " " (List.filter (fun s -> not (String.equal s "")) (String.split_on_char '\n' s))

(* a diagnostic from an Elpi location; an error located in another file (an
   accumulated one) is shown on the accumulate directive of the document that
   brings that file in ([accumulated], see LSP.accumulated), or at the
   beginning of the document *)
let diag_of_loc ~path ~accumulated severity loc message =
  let message = String.trim message in
  match loc with
  | Some { Ast.Loc.source_name; source_start; source_stop; _ } when String.equal source_name path ->
      { start = source_start; stop = source_stop; severity; message }
  | Some { Ast.Loc.source_name; line; source_start; line_starts_at; _ } ->
      let start, stop =
        match List.find_opt (fun (_, files) -> List.exists (String.equal source_name) files) accumulated with
        | Some ((l : Ast.Loc.t), _) -> l.source_start, l.source_stop
        | None -> 0, 0 in
      { start; stop; severity;
        message = Printf.sprintf "In %s, line %d, column %d: %s" source_name line
            (source_start - line_starts_at + 1) message }
  | None -> { start = 0; stop = 0; severity; message }

(* a syntax error is a position: its diagnostic covers the word there *)
let syntax_diagnostics ~path ~accumulated text (errors : Error.t list) =
  let t = Text.make text in
  List.map (fun (e : Error.t) ->
    let d = diag_of_loc ~path ~accumulated Error e.loc (one_line (Format.asprintf "%a" Error.pp_message e)) in
    match e.loc with
    | Some loc when String.equal loc.source_name path && Int.equal d.stop d.start -> { d with stop = Text.word_end t d.start }
    | _ -> d)
    errors

(* --- checking --------------------------------------------------------------- *)

(* the maximum number of errors reported for a compilation unit (a file), the
   compiler stops there *)
let max_errors = ref 100

let resilient_parse ~elpi ~path text =
  let lexbuf = Lexing.from_string text in
  let flags = { Compile.default_flags with Compile.max_errors = !max_errors } in
  Parse.program_from ~flags ~elpi ~loc:(Ast.Loc.initial path) ~digest:(Digest.string text) lexbuf


(* the per-phase timings are logged with the environment variable, or when
   the client asks for traces (the setting elpi-lsp.debug of VS Code) *)
let profile = ref (Option.is_some (Sys.getenv_opt "ELPI_LSP_PROFILE"))
let verbose = ref false
let set_trace = function
  | Lsp.Types.TraceValues.Off -> profile := Option.is_some (Sys.getenv_opt "ELPI_LSP_PROFILE"); verbose := false
  | Lsp.Types.TraceValues.Messages | Compact -> profile := true; verbose := false
  | Lsp.Types.TraceValues.Verbose -> profile := true; verbose := true

let timed what f =
  if not !profile then f () else begin
    let t = Unix.gettimeofday () in
    let r = f () in
    log "  %s: %.3fs" what (Unix.gettimeofday () -. t); r
  end


(* An error of the compiler, as a location and a message *)
let error_of_exn = function
  | Parse.ParseError (loc, msg) -> Some loc, msg
  | Error.ElpiError ({ loc } as e) -> loc, Format.asprintf "%a" Error.pp_message e
  | Failure msg -> None, msg
  | e ->
      log "internal error: %s\n%s" (Printexc.to_string e) (Printexc.get_backtrace ());
      None, "internal error: " ^ Printexc.to_string e

let compile_unit ?(extend = true) ~elpi ~cache ~flags ~key ~base sp =
  let name = Filename.basename (Compile.scoped_program_name sp) in
  match cache_find cache key with
  | Some c ->
      if !verbose then log "  unit %s: cached" name;
      c
  | None ->
      (* the passes are error resilient (their errors, ElpiError, are in the
         result), but they can still raise another exception (a bug, e.g.
         Not_found): then the unit is dropped (the program is not extended
         with it) and the exception is its error *)
      let failed e =
        let loc, message = error_of_exn e in
        [ { Error.component = ""; loc; message } ] in
      let u, extended, errors, warnings =
        match timed ("unit " ^ name) (fun () -> Compile.unit ~elpi ~flags ~base sp) with
        | exception e -> None, base, failed e, []
        | u, e1, w1 ->
            match if extend then timed ("extend " ^ name) (fun () -> Compile.extend ~flags ~base u)
                  else base, [], [] with
            | exception e -> Some u, base, e1 @ failed e, w1
            | extended, e2, w2 -> Some u, extended, e1 @ e2, w1 @ w2 in
      if !verbose then log "  unit %s: %d errors" name (List.length errors);
      let info = lazy (match u with
          | Some u -> timed ("hover " ^ name) (fun () -> LSP.hover ~base sp u)
          | None -> LSP.IntervalTree.of_list []) in
      let c = { extended; errors; warnings; info } in
      cache_add cache key c;
      c

(* The compiler passes return all the errors they find, and a unit without the
   items that are wrong: the program is compiled once. *)
let compile ~instance:{ elpi; cache } ~path ~accumulated ast =
  let flags = { Compile.default_flags with
                Compile.max_errors = !max_errors;
                skip_det_checking = !is_library_path path } in
  let sps, e0, w0 = timed "scope" (fun () -> Compile.scope_ast ~elpi ~flags ast) in
  let extend = not (!is_library_path path) in
  (* the flags that change the result of compile_unit start the key *)
  let flags_key = Printf.sprintf "max_errors=%d skip_det_checking=%b extend=%b"
      flags.Compile.max_errors flags.Compile.skip_det_checking extend in
  let _, _, errors, warnings, infos =
    List.fold_left (fun (key, base, errors, warnings, infos) sp ->
        let key = Digest.string (key ^ Compile.scoped_program_digest sp) in
        let c = compile_unit ~extend ~elpi ~cache ~flags ~key ~base:base sp in
        key, c.extended, errors @ c.errors, warnings @ c.warnings, c.info :: infos)
      (flags_key, Compile.empty_base ~elpi, e0, w0, []) sps in
  errors, warnings, List.rev infos

let diag_of_error ~path ~accumulated severity (e : Error.t) =
  diag_of_loc ~path ~accumulated severity e.loc (Format.asprintf "%a" Error.pp_message e)

(* The warning about an undeclared global is at its first occurrence (the
   application whose head it is): it is shown on all its occurrences, the ones
   of the constant that starts there in the hover information (where its
   origin is User: its type, inferred, is added to the program) *)
let spread_undeclared (hover : unit_info list) ({ Error.warning_id; warning } : Error.warning) =
  match warning_id, warning.loc with
  | Error.UndeclaredGlobal, Some (loc : Ast.Loc.t) ->
      let start = { loc with source_stop = loc.source_start } in
      let occurrences =
        List.concat_map (fun u -> LSP.IntervalTree.find start (Lazy.force u)) hover
        |> List.find_map (fun ((l : Ast.Loc.t), (i : LSP.info)) ->
            match i.kind with
            | LSP.Constant _ when Int.equal l.source_start loc.source_start -> Some i.occurrences
            | _ -> None) in
      (match occurrences with
       | Some (_ :: _ as ls) -> List.map (fun l -> { warning with Error.loc = Some l }) ls
       | _ -> [ warning ])
  | _ -> [ warning ]

let check ~instance ~path text =
  (* the resilient parser does not fail, but for robustness the exception is
     reported as an error *)
  match resilient_parse ~elpi:instance.elpi ~path text with
  | exception e ->
      let loc, msg = error_of_exn e in
      { diagnostics = [ diag_of_loc ~path ~accumulated:[] Error loc msg ]; hover = None }
  | ast, parse_errors, parse_warnings ->
      let accumulated = LSP.accumulated ast in
      let syntax = syntax_diagnostics ~path ~accumulated text parse_errors in
      let errors, warnings, hover = compile ~instance ~path ~accumulated ast in
      let errors = List.map (diag_of_error ~path ~accumulated Error) errors in
      let ws = List.concat_map (fun w -> List.map (diag_of_error ~path ~accumulated Warning) (spread_undeclared hover w))
          (parse_warnings @ warnings) in
      { diagnostics = syntax @ errors @ ws; hover = Some hover }

(* --- queries on the symbols --------------------------------------------------- *)

let is_variable (i : LSP.info) =
  match i.kind with LSP.Bound | Binder | Unification_variable -> Option.is_some i.defined | _ -> false
let is_constant (i : LSP.info) = match i.kind with LSP.Constant _ -> true | _ -> false

(* The information of [path] at byte [off] satisfying [p]: the ones that
   contain it, smallest first, or else the ones that end at [off] (the cursor
   just after a word). *)
let infos_at ~path off p (hover : hover) =
  let loc = { (Ast.Loc.initial path) with source_start = off; source_stop = off } in
  let infos = List.concat_map (fun u -> LSP.IntervalTree.find loc (Lazy.force u)) hover
              |> List.filter (fun (_, i) -> p i) in
  let size ((l : Ast.Loc.t), _) = l.source_stop - l.source_start in
  let inside = List.filter (fun ((l : Ast.Loc.t), _) -> l.source_start <= off && off < l.source_stop) infos in
  List.stable_sort (fun x y -> Int.compare (size x) (size y)) (if inside <> [] then inside else infos)

let innermost ~path off p hover =
  match infos_at ~path off p hover with x :: _ -> Some x | [] -> None

(* the binder of a variable, with the backslash that follows it *)
let complete_binder text (l : Ast.Loc.t) =
  let n = String.length text in
  let rec skip i = if i < n && (Char.equal text.[i] ' ' || Char.equal text.[i] '\t') then skip (i + 1) else i in
  let j = skip l.source_stop in
  if not (String.equal l.source_name "") && j < n && Char.equal text.[j] '\\' then { l with source_stop = j + 1 } else l

(* what to say about a variable, from the text of the document *)
let binder_description text (i : LSP.info) =
  match i.kind, i.defined with
  | (LSP.Bound | Binder), Some d when d.source_stop <= String.length text ->
      let d = complete_binder text d in
      Some (Printf.sprintf "bound by `%s`" (String.trim (String.sub text d.source_start (d.source_stop - d.source_start))))
  | Unification_variable, Some d when d.source_stop <= String.length text ->
      Some (Printf.sprintf "variable of the rule `%s`" (one_line (String.trim (String.sub text d.source_start (d.source_stop - d.source_start)))))
  | _ -> None

(* [shorten n t] has at most [n] characters: the middle of [t] is replaced by
   "..." if it is longer *)
let shorten n t =
  let len = String.length t in
  if len <= n then t
  else
    (* cut on the boundary of a UTF-8 character *)
    let rec boundary i = if i > 0 && i < len && Int.equal (Char.code t.[i] land 0xC0) 0x80 then boundary (i - 1) else i in
    let head = boundary ((n - 3) / 2) and tail = boundary (len - (n - 3 - (n - 3) / 2)) in
    String.sub t 0 head ^ "..." ^ String.sub t tail (len - tail)

(* what is shown on hover *)
type hover_text = {
  range : Ast.Loc.t;       (* what the text is about, highlighted by the client *)
  term : string option;    (* the text of [range], for a term *)
  type_ : string;          (* the type of a term, what a type expression says *)
  binder : string option;  (* for a variable, where it is bound *)
  doc : Ast.Loc.t option;  (* for a constant, the comment block before its declaration *)
}

(* The innermost information with a type (a term, a symbol of a rule) or a
   text (a type expression). The type of a term is printed only here: the
   information at a position is about all the terms around it, one is shown. *)
let hover_at ~path ~text off hover =
  (* the term that the type is the type of: the hover range is highlighted by
     the client, and the term is quoted in the popup, to make clear what it is
     about (eg a whole application when the cursor is on a blank) *)
  let quote (loc : Ast.Loc.t) =
    if loc.source_stop > String.length text then None
    else Some (shorten 20 (one_line (String.sub text loc.source_start (loc.source_stop - loc.source_start)))) in
  match innermost ~path off (fun i -> Option.is_some i.description) hover with
  | Some (loc, ({ description = Some (LSP.Text t); _ } : LSP.info)) ->
      Some { range = loc; term = None; type_ = t; binder = None; doc = None }
  | Some (loc, ({ description = Some (LSP.Type ty); doc; _ } as i)) ->
      let binder = if is_variable i then binder_description text i else None in
      Some { range = loc; term = quote loc; type_ = Format.asprintf "%a" LSP.pp_type_ ty; binder; doc }
  | _ -> None

(* the text of a comment block (at [loc] in [text]) without the comment
   markers: the % of each line (and a space after it), or the /* */ *)
let doc_text text (loc : Ast.Loc.t) =
  if loc.source_stop > String.length text || loc.source_start > loc.source_stop then ""
  else
    let s = String.sub text loc.source_start (loc.source_stop - loc.source_start) in
    let strip_prefix p s =
      if String.length s >= String.length p && String.equal (String.sub s 0 (String.length p)) p
      then String.sub s (String.length p) (String.length s - String.length p) else s in
    let strip_suffix p s =
      let n = String.length s and m = String.length p in
      if n >= m && String.equal (String.sub s (n - m) m) p then String.sub s 0 (n - m) else s in
    let line l =
      let l = String.trim l in
      if String.length l > 0 && Char.equal l.[0] '%' then strip_prefix " " (String.sub l 1 (String.length l - 1)) else l in
    let s = String.trim s in
    let s = if String.length s >= 2 && String.equal (String.sub s 0 2) "/*" then String.trim (strip_suffix "*/" (strip_prefix "/*" s)) else s in
    String.concat "\n" (List.map line (String.split_on_char '\n' s)) |> String.trim

(* the declaration of a symbol (with the body of a constant); the binder of a
   variable, the head of the rule of a unification variable *)
let definition_at ~path off hover =
  Option.bind (innermost ~path off (fun i -> Option.is_some i.defined) hover)
    (fun (loc, (i : LSP.info)) -> Option.map (fun d -> loc, d, i.body) i.defined)

type highlight =
  | Binder_of_variable of Ast.Loc.t   (* the binder, or the head of the rule *)
  | Definition_of_constant of Ast.Loc.t  (* the declaration, when it is in the document *)
  | Occurrence of Ast.Loc.t

(* The occurrences of the variable or constant at [off] (the compiler groups
   them by name and binder, or declaration), and its binder or definition
   site. The occurrences are the ones in the unit of [off], in the document.
   The declaration of a constant is highlighted only if it is in the
   document. *)
let highlights_at ~path off (hover : hover) =
  (* among the symbols at [off] (not the terms), the first variable or constant:
     on a keyword just after a variable, it is not that variable *)
  let symbols = infos_at ~path off (fun (i : LSP.info) -> match i.kind with LSP.Term -> false | _ -> true) hover in
  match List.find_opt (fun (_, i) -> is_variable i || is_constant i) symbols with
  | None -> []
  | Some (_, v) ->
      let occurrences = List.filter (fun (l : Ast.Loc.t) -> String.equal l.source_name path) v.occurrences in
      let definition =
        match v.defined with
        | Some d when is_variable v -> [ Binder_of_variable d ]
        | Some d when String.equal d.source_name path -> [ Definition_of_constant d ]
        | _ -> [] in
      definition @ List.map (fun l -> Occurrence l) occurrences

(* --- semantic tokens ----------------------------------------------------------- *)

type token_type =
  | Function | EnumMember | Parameter | Variable | Keyword | Number | String
  | Type | TypeParameter | Macro

let token_type_name = function
  | Function -> "function" | EnumMember -> "enumMember" | Parameter -> "parameter"
  | Variable -> "variable" | Keyword -> "keyword" | Number -> "number" | String -> "string"
  | Type -> "type" | TypeParameter -> "typeParameter" | Macro -> "macro"

(* the code of a type in the protocol: its index in the legend *)
let token_code = function
  | Function -> 0 | EnumMember -> 1 | Parameter -> 2 | Variable -> 3 | Keyword -> 4
  | Number -> 5 | String -> 6 | Type -> 7 | TypeParameter -> 8 | Macro -> 9

(* The legend sent to the client *)
let token_types =
  [ Function; EnumMember; Parameter; Variable; Keyword; Number; String; Type; TypeParameter; Macro ]
  |> List.sort (fun a b -> Int.compare (token_code a) (token_code b))
  |> List.map token_type_name
let token_modifiers = [ "declaration" ]

(* The type of the token of a symbol, if it has one: the predicates and
   functions that a rule defines are functions, the data constants are enum
   members, bound variables are parameters, the variables of a rule are
   variables. The nodes that cover
   more than a word (the type of a declaration) are not tokens. *)
let token_type (n : LSP.info) =
  match n.kind with
  | LSP.Constant (Predicate, _) | Constant (Function, _) ->
      (* only the symbol that a rule defines: in the body of the rules they are
         too many *)
      if n.declaration then Some Function else None
  | Constant (Data, _) -> Some EnumMember
  | Bound | Binder -> Some Parameter
  | Unification_variable -> Some Variable
  | Keyword -> Some Keyword
  | Literal (`Int | `Float) -> Some Number
  | Literal `String -> Some String
  | Term | Literal `Other | Discard | Type_keyword -> None
  | Macro -> Some Macro
  | Type_constructor | Type_abbreviation -> Some Type
  | Type_variable -> Some TypeParameter

(* The tokens of the document, as the data of the protocol: for each one, the
   line and the column (UTF-16 units) relative to the previous one, the length,
   the type and the modifiers. Tokens that overlap or span lines are dropped. *)
let semantic_tokens ~path (text : Text.t) (hover : hover) =
  let tokens =
    List.concat_map (fun u ->
        LSP.IntervalTree.fold_file path (fun (loc : Ast.Loc.t) (n : LSP.info) acc ->
            match token_type n with
            | Some t -> (loc.source_start, loc.source_stop, t, n.declaration) :: acc
            | None -> acc)
          (Lazy.force u) []) hover in
  let compare_token (s1, e1, t1, d1) (s2, e2, t2, d2) =
    match Int.compare s1 s2 with
    | 0 -> (match Int.compare e1 e2 with
           | 0 -> (match Int.compare (token_code t1) (token_code t2) with 0 -> Bool.compare d1 d2 | c -> c)
           | c -> c)
    | c -> c in
  let tokens = List.sort_uniq compare_token tokens in
  let data = ref [] and last_line = ref 0 and last_col = ref 0 and last_stop = ref (-1) in
  List.iter (fun (start, stop, t, declaration) ->
      let p1 = Text.position_of_offset text start and p2 = Text.position_of_offset text stop in
      if start >= !last_stop && stop > start && Int.equal p1.Lsp.Types.Position.line p2.Lsp.Types.Position.line then begin
        let line = p1.line and col = p1.character in
        let delta_col = if Int.equal line !last_line then col - !last_col else col in
        data := (if declaration then 1 else 0) :: token_code t :: (p2.character - col) :: delta_col :: (line - !last_line) :: !data;
        last_line := line; last_col := col; last_stop := stop
      end) tokens;
  Array.of_list (List.rev !data)
