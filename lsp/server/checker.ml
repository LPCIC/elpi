(* Checking a document with Elpi: error-resilient parsing first (a
   declaration with a syntax error is skipped, see API.Parse.program_from),
   then compilation (scoping and type checking) as a unit through the API of
   the program without the erroneous declarations, so that type errors, hover
   and definition are available even when the text has syntax errors. The
   result is a list of diagnostics, as byte offsets in the text, and, when the
   program compiles, the hover information. *)

open Elpi.API

type severity = Error | Warning | Information

type diagnostic = {
  start : int;   (* byte offsets in the document *)
  stop : int;
  severity : severity;
  message : string;
}

(* the information on the units of the program (the accumulated files, then the
   document), computed when asked:
   - hover and go to definition use the interval trees [rules] (the rules) and
     [types] (the declarations), that are cheap;
   - [nodes] and [tree] have all the symbols (Compile.iter), they are needed
     for the variables: highlights, binders *)
type unit_info = {
  rules : Compile.info Compile.IntervalTree.t Lazy.t;
  types : (string * Ast.Loc.t option) Compile.IntervalTree.t Lazy.t;
  nodes : Compile.node list Lazy.t;
  tree : Compile.node Compile.IntervalTree.t Lazy.t;
}

type hover = unit_info list

type result = {
  diagnostics : diagnostic list;
  hover : hover option; (* when the text compiles *)
}

let log fmt = Printf.ksprintf (fun s -> prerr_endline ("[elpi-lsp] " ^ s)) fmt

(* --- Elpi instance -------------------------------------------------------- *)

(* The error hooks of Elpi exit by default: we turn errors into exceptions,
   and collect warnings. *)
exception Elpi_error of Ast.Loc.t option * string

let warnings = ref []

let () =
  Setup.set_error (fun ?loc msg -> raise (Elpi_error (loc, msg)));
  Setup.set_type_error (fun ?loc msg -> raise (Elpi_error (loc, msg)));
  Setup.set_anomaly (fun ?loc msg -> raise (Elpi_error (loc, "anomaly: " ^ msg)));
  Setup.set_warn (fun ?loc ~id:_ msg -> warnings := (loc, msg) :: !warnings);
  Setup.set_std_formatter Format.err_formatter

(* accumulated files are resolved relative to the accumulating file (the
   parser passes its directory as ~cwd), then in TJPATH *)
let tjpath =
  match Sys.getenv_opt "TJPATH" with
  | None -> []
  | Some v -> List.filter (fun s -> s <> "") (String.split_on_char ':' v)

let resolver = Parse.std_resolver ~paths:tjpath ()

let elpi = lazy (Setup.init ~builtins:[Elpi.Builtin.std_builtins] ~file_resolver:resolver ())

(* --- the files of the standard library ------------------------------------- *)

(* The builtins and the standard library are not in files that the server can
   read, but the text of the file "builtin.elpi" is generated by Elpi
   (BuiltIn.document_fmt: the declarations of the builtins written in OCaml,
   and the code of the library). It is the text that the compiler parsed, so
   the locations of the symbols of the library are in it. The #line directives
   split it in files (builtin_stdlib.elpi, ...), as the locations see them:
   positions start from 0 after the directive. Each transport shows these files
   to the editor in its own way (written on the disk, or served by the
   server). They are computed the first time they are needed. *)
let library_files_cache : (string, string) Hashtbl.t option ref = ref None

let compute_library_files () =
  let b = Buffer.create 100_000 in
  let fmt = Format.formatter_of_buffer b in
  BuiltIn.document_fmt fmt Elpi.Builtin.std_builtins;
  Format.pp_print_flush fmt ();
  let files = Hashtbl.create 7 in
  let current = ref "builtin.elpi" and text = Buffer.create 100_000 in
  let flush () =
    Hashtbl.replace files !current
      ((Option.value ~default:"" (Hashtbl.find_opt files !current)) ^ Buffer.contents text);
    Buffer.clear text in
  (* #line N "file" gives the file *)
  let directive line =
    if String.length line > 6 && String.sub line 0 6 = "#line " then
      match String.split_on_char '"' line with
      | [ _; file; "" ] -> Some file
      | _ -> None
    else None in
  List.iter (fun line ->
      match directive line with
      | Some file -> flush (); current := Filename.basename file
      | None -> Buffer.add_string text line; Buffer.add_char text '\n')
    (String.split_on_char '\n' (Buffer.contents b));
  flush ();
  files

let library_files () =
  match !library_files_cache with
  | Some files -> files
  | None -> let files = compute_library_files () in library_files_cache := Some files; files

(* the text of the file of the library [name] (eg builtin_stdlib.elpi) *)
let library_text name = Hashtbl.find_opt (library_files ()) (Filename.basename name)

(* whether [path] is a file of the library, opened by the editor: it is not
   meant to be edited, nor checked for determinacy. Each transport shows the
   library files to the editor in its own way, and sets it. *)
let is_library_path : (string -> bool) ref = ref (fun _ -> false)

(* --- diagnostics ------------------------------------------------------------ *)

let one_line s = String.concat " " (List.filter (( <> ) "") (String.split_on_char '\n' s))

(* a diagnostic from an Elpi location; an error located in another file (an
   accumulated one) is shown on the accumulate directive of the document that
   brings that file in ([accumulated], see Parse.accumulated), or at the
   beginning of the document *)
let diag_of_loc ~path ~accumulated severity loc message =
  let message = String.trim message in
  match loc with
  | Some { Ast.Loc.source_name; source_start; source_stop; _ } when source_name = path ->
      { start = source_start; stop = source_stop; severity; message }
  | Some { Ast.Loc.source_name; line; source_start; line_starts_at; _ } ->
      let start, stop =
        match List.find_opt (fun (_, files) -> List.mem source_name files) accumulated with
        | Some ((l : Ast.Loc.t), _) -> l.source_start, l.source_stop
        | None -> 0, 0 in
      { start; stop; severity;
        message = Printf.sprintf "In %s, line %d, column %d: %s" source_name line
            (source_start - line_starts_at + 1) message }
  | None -> { start = 0; stop = 0; severity; message }

(* a syntax error is a position: its diagnostic covers the word there *)
let syntax_diagnostics ~path ~accumulated text (errors : Parse.error list) =
  let t = Text.make text in
  List.map (fun (e : Parse.error) ->
    let d = diag_of_loc ~path ~accumulated Error e.loc (one_line (Format.asprintf "%a" Compile.pp_error_message e)) in
    match e.loc with
    | Some loc when loc.source_name = path && d.stop = d.start -> { d with stop = Text.word_end t d.start }
    | _ -> d)
    errors

(* --- checking --------------------------------------------------------------- *)

(* the maximum number of errors reported for a compilation unit (a file), the
   compiler stops there *)
let max_errors = ref 100

let resilient_parse ~path text =
  let elpi = Lazy.force elpi in
  let lexbuf = Lexing.from_string text in
  let flags = { Compile.default_flags with Compile.max_errors = !max_errors } in
  Parse.program_from ~flags ~elpi ~loc:(Ast.Loc.initial path) ~digest:(Digest.string text) lexbuf


(* the per-phase timings are logged with the environment variable, or when
   the client asks for traces (the setting elpi-lsp.debug of VS Code) *)
let profile = ref (Sys.getenv_opt "ELPI_LSP_PROFILE" <> None)
let verbose = ref false
let set_trace = function
  | Lsp.Types.TraceValues.Off -> profile := Sys.getenv_opt "ELPI_LSP_PROFILE" <> None; verbose := false
  | Lsp.Types.TraceValues.Messages | Compact -> profile := true; verbose := false
  | Lsp.Types.TraceValues.Verbose -> profile := true; verbose := true

let timed what f =
  if not !profile then f () else begin
    let t = Unix.gettimeofday () in
    let r = f () in
    log "  %s: %.3fs" what (Unix.gettimeofday () -. t); r
  end

(* A cache of compiled units. A program is a list of units (the accumulated
   files, then the document), each compiled on top of the previous ones. A
   unit is identified by its digest, those of the units before it and the
   flags of the compilation: if none changed, its compilation (the program
   extended with it, its errors and warnings) is reused. So an accumulated file is compiled once, not at each
   check. The unit itself is kept: its symbols are computed when needed. *)
type cached_unit = {
  extended : Compile.program;
  errors : Compile.error list;
  unit_warnings : (Ast.Loc.t option * string) list;
  info : unit_info;
}

(* The cache is bounded, the least recently used unit is evicted: each edit
   of a document makes a new key for its unit (and for the units after it),
   and an entry holds a whole program. [cache_size] units are enough for the
   accumulated files of the open documents, and a few versions of them. *)
let cache_size = 64
let unit_cache : (Digest.t, cached_unit * int ref) Hashtbl.t = Hashtbl.create 17
let cache_clock = ref 0

let cache_find key =
  match Hashtbl.find_opt unit_cache key with
  | None -> None
  | Some (c, last_use) -> incr cache_clock; last_use := !cache_clock; Some c

let cache_add key c =
  if Hashtbl.length unit_cache >= cache_size then begin
    let oldest = Hashtbl.fold (fun k (_, t) acc ->
        match acc with Some (_, t') when t' <= !t -> acc | _ -> Some (k, !t)) unit_cache None in
    Option.iter (fun (k, _) -> Hashtbl.remove unit_cache k) oldest
  end;
  incr cache_clock;
  Hashtbl.replace unit_cache key (c, ref !cache_clock)

(* [with_own_warnings f] is the result of [f ()] and the warnings that it
   emitted, which are also added to [warnings] *)
let with_own_warnings f =
  let outer = !warnings in
  warnings := [];
  match f () with
  | r -> let own = !warnings in warnings := own @ outer; r, own
  | exception e -> warnings := !warnings @ outer; raise e

let nodes_of sp u =
  let l = ref [] in
  Compile.iter sp u (fun n -> l := n :: !l);
  !l

let compile_unit ?(extend = true) ~elpi ~flags ~key ~base sp =
  let name = Filename.basename (Compile.scoped_program_name sp) in
  match cache_find key with
  | Some c ->
      if !verbose then log "  unit %s: cached" name;
      warnings := c.unit_warnings @ !warnings; c
  | None ->
      let (u, extended, e1, e2), unit_warnings = with_own_warnings (fun () ->
        let u, e1 = timed ("unit " ^ name) (fun () -> Compile.unit ~elpi ~flags ~base sp) in
        let extended, e2 =
          if extend then timed ("extend " ^ name) (fun () -> Compile.extend ~flags ~base u)
          else base, [] in
        u, extended, e1, e2) in
      if !verbose then log "  unit %s: %d errors" name (List.length e1 + List.length e2);
      let rules = lazy (timed ("hover " ^ name) (fun () -> Compile.hover u)) in
      let types = lazy (timed ("types " ^ name) (fun () ->
        Compile.IntervalTree.of_list (List.map (fun (l, t, d) -> l, (t, d)) (Compile.hover_types sp)))) in
      let nodes = lazy (timed ("symbols " ^ name) (fun () -> nodes_of sp u)) in
      let tree = lazy (Compile.IntervalTree.of_list (List.map (fun (n : Compile.node) -> n.loc, n) (Lazy.force nodes))) in
      let c = { extended; errors = e1 @ e2; unit_warnings; info = { rules; types; nodes; tree } } in
      cache_add key c;
      c

(* An error of the compiler, as a location and a message *)
let error_of_exn = function
  | Parse.ParseError (loc, msg) -> Some loc, msg
  | Compile.CompileError ({ loc } as e) -> loc, Format.asprintf "%a" Compile.pp_error_message e
  | Elpi_error (loc, msg) -> loc, msg
  | Failure msg -> None, msg
  | e ->
      log "internal error: %s\n%s" (Printexc.to_string e) (Printexc.get_backtrace ());
      None, "internal error: " ^ Printexc.to_string e

(* The compiler passes return all the errors they find, and a unit without the
   items that are wrong: the program is compiled once. *)
let compile ~path ~accumulated ast =
  let elpi = Lazy.force elpi in
  let flags = { Compile.default_flags with
                Compile.max_errors = !max_errors;
                skip_det_checking = !is_library_path path } in
  let sps, e0 = timed "scope" (fun () -> Compile.scope_ast ~elpi ~flags ast) in
  let extend = not (!is_library_path path) in
  (* the flags that change the result of compile_unit start the key *)
  let flags_key = Printf.sprintf "max_errors=%d skip_det_checking=%b extend=%b"
      flags.Compile.max_errors flags.Compile.skip_det_checking extend in
  let _, _, errors, infos =
    List.fold_left (fun (key, base, errors, infos) sp ->
        let key = Digest.string (key ^ Compile.scoped_program_digest sp) in
        let c = compile_unit ~extend ~elpi ~flags ~key ~base:base sp in
        key, c.extended, errors @ c.errors, c.info :: infos)
      (flags_key, Compile.empty_base ~elpi, e0, []) sps in
  let diag (e : Compile.error) =
    diag_of_loc ~path ~accumulated Error e.loc (Format.asprintf "%a" Compile.pp_error_message e) in
  List.map diag errors, List.rev infos

let check ~path text =
  (* the resilient parser does not fail, but for robustness the exception is
     reported as an error *)
  match resilient_parse ~path text with
  | exception e ->
      let loc, msg = error_of_exn e in
      { diagnostics = [ diag_of_loc ~path ~accumulated:[] Error loc msg ]; hover = None }
  | ast, parse_errors ->
      let accumulated = Parse.accumulated ast in
      let syntax = syntax_diagnostics ~path ~accumulated text parse_errors in
      warnings := [];
      let errors, hover = compile ~path ~accumulated ast in
      let ws = List.rev_map (fun (loc, msg) -> diag_of_loc ~path ~accumulated Warning loc msg) !warnings in
      warnings := [];
      { diagnostics = syntax @ errors @ ws; hover = Some hover }

(* --- queries on the symbols --------------------------------------------------- *)

(* The symbols of [path] at byte [off]: the ones that contain it, smallest
   first, or else the ones that end at [off] (the cursor just after a word). *)
let nodes_at ~path off (hover : hover) : Compile.node list =
  let loc = { (Ast.Loc.initial path) with source_start = off; source_stop = off } in
  let nodes = List.concat_map (fun u -> List.map snd (Compile.IntervalTree.find loc (Lazy.force u.tree))) hover in
  let size (n : Compile.node) = n.loc.source_stop - n.loc.source_start in
  let inside = List.filter (fun (n : Compile.node) -> n.loc.source_start <= off && off < n.loc.source_stop) nodes in
  List.stable_sort (fun x y -> compare (size x) (size y)) (if inside <> [] then inside else nodes)

(* the binder of a variable, with the backslash that follows it *)
let complete_binder text (l : Ast.Loc.t) =
  let n = String.length text in
  let rec skip i = if i < n && (text.[i] = ' ' || text.[i] = '\t') then skip (i + 1) else i in
  let j = skip l.source_stop in
  if l.source_name <> "" && j < n && text.[j] = '\\' then { l with source_stop = j + 1 } else l

(* what to say about a variable, from the text of the document *)
let binder_description text (n : Compile.node) =
  match n.kind, n.defined with
  | (Compile.Bound | Binder), Some d when d.source_stop <= String.length text ->
      let d = complete_binder text d in
      Some (Printf.sprintf "bound by `%s`" (String.trim (String.sub text d.source_start (d.source_stop - d.source_start))))
  | Unification_variable, Some d when d.source_stop <= String.length text ->
      Some (Printf.sprintf "variable of the rule `%s`" (one_line (String.trim (String.sub text d.source_start (d.source_stop - d.source_start)))))
  | _ -> None

(* An entry of the hover information: the rules give the type of each
   sub-expression (a term) and the declaration of its head, the declarations
   a text for each type expression *)
type entry = {
  loc : Ast.Loc.t;
  text : string option;        (* the type of a term, what a type expression says *)
  defined : Ast.Loc.t option;  (* the declaration *)
  is_term : bool;              (* a sub-expression of a rule *)
}

(* The entries at byte [off] of [path]; the innermost one with a text (for
   hover) or a definition is chosen: among the intervals containing [off], or
   else ending at [off] (the cursor just after a word). *)
let entries ~path off (hover : hover) =
  let loc = { (Ast.Loc.initial path) with source_start = off; source_stop = off } in
  let terms =
    List.concat_map (fun u -> Compile.IntervalTree.find loc (Lazy.force u.rules)) hover
    |> List.map (fun (loc, (i : Compile.info)) ->
        { loc; text = Option.map (Format.asprintf "%a" Compile.pp_type_) i.type_; defined = i.defined; is_term = true }) in
  let types =
    List.concat_map (fun u -> Compile.IntervalTree.find loc (Lazy.force u.types)) hover
    |> List.map (fun (loc, (text, defined)) -> { loc; text = Some text; defined; is_term = false }) in
  terms @ types

let innermost ~path off p hover =
  let entries = List.filter p (entries ~path off hover) in
  let size { loc; _ } = loc.source_stop - loc.source_start in
  let inside = List.filter (fun { loc; _ } -> loc.source_start <= off && off < loc.source_stop) entries in
  let candidates = if inside <> [] then inside else entries in
  match List.stable_sort (fun x y -> compare (size x) (size y)) candidates with
  | x :: _ -> Some x
  | [] -> None

(* The variable at [off], if any (this needs the symbols of the units): the
   cursor is on it, or, with [~loc], the variable is exactly [loc] (the range
   of a hover: when it is a bigger expression, an expression that has a
   variable at its end is not about that variable). *)
let variable_at ?loc ~path off hover =
  let here (n : Compile.node) =
    match loc with
    | Some (l : Ast.Loc.t) -> n.loc.source_start = l.source_start && n.loc.source_stop = l.source_stop
    | None -> n.loc.source_start <= off && off < n.loc.source_stop in
  List.find_opt (fun (n : Compile.node) ->
    here n && (match n.kind with Compile.Bound | Binder | Unification_variable -> n.defined <> None | _ -> false))
    (nodes_at ~path off hover)

(* [shorten n t] has at most [n] characters: the middle of [t] is replaced by
   "..." if it is longer *)
let shorten n t =
  let len = String.length t in
  if len <= n then t
  else
    (* cut on the boundary of a UTF-8 character *)
    let rec boundary i = if i > 0 && i < len && Char.code t.[i] land 0xC0 = 0x80 then boundary (i - 1) else i in
    let head = boundary ((n - 3) / 2) and tail = boundary (len - (n - 3 - (n - 3) / 2)) in
    String.sub t 0 head ^ "..." ^ String.sub t tail (len - tail)

(* what is shown on hover *)
type hover_text = {
  range : Ast.Loc.t;       (* what the text is about, highlighted by the client *)
  term : string option;    (* the text of [range], for a term *)
  type_ : string;          (* the type of a term, what a type expression says *)
  binder : string option;  (* for a variable, where it is bound *)
}

let hover_at ~path ~text off hover =
  (* the term that the type is the type of: the hover range is highlighted by
     the client, and the term is quoted in the popup, to make clear what it is
     about (eg a whole application when the cursor is on a blank) *)
  let quote (loc : Ast.Loc.t) is_term =
    if not is_term || loc.source_stop > String.length text then None
    else
      let t = one_line (String.sub text loc.source_start (loc.source_stop - loc.source_start)) in
      Some (shorten 20 t) in
  match innermost ~path off (fun e -> e.text <> None) hover with
  | Some { loc; text = Some type_; defined = None; is_term } ->
      (* a variable, a literal, ...: only a variable has a binder *)
      let binder = Option.bind (variable_at ~loc ~path off hover) (binder_description text) in
      Some { range = loc; term = quote loc is_term; type_; binder }
  | Some { loc; text = Some type_; defined = Some _; is_term } ->
      Some { range = loc; term = quote loc is_term; type_; binder = None }
  | _ -> None

(* the declaration of a symbol; the binder of a variable, the head of the rule
   of a unification variable (from the symbols) *)
let definition_at ~path off hover =
  match innermost ~path off (fun e -> e.defined <> None) hover with
  | Some { loc; defined = Some d; _ } -> Some (loc, d)
  | _ ->
      Option.bind (variable_at ~path off hover) (fun (n : Compile.node) ->
        Option.map (fun d -> n.loc, d) n.defined)

type highlight =
  | Binder_of_variable of Ast.Loc.t   (* the binder, or the head of the rule *)
  | Definition_of_constant of Ast.Loc.t  (* the declaration, when it is in the document *)
  | Occurrence of Ast.Loc.t

(* The occurrences of the variable or constant at [off], and its binder or
   definition site: the occurrences are the nodes with the same name and
   binder (or declaration). The declaration of a constant is highlighted only
   if it is in the document. *)
let highlights_at ~path off (hover : hover) =
  let is_variable (n : Compile.node) =
    match n.kind with Compile.Bound | Binder | Unification_variable -> n.defined <> None | _ -> false in
  let is_constant (n : Compile.node) = match n.kind with Compile.Constant _ -> true | _ -> false in
  match List.find_opt (fun n -> is_variable n || is_constant n) (nodes_at ~path off hover) with
  | None -> []
  | Some v ->
      let same (n : Compile.node) =
        (if is_variable v then is_variable n else is_constant n)
        && n.kind <> Compile.Binder && n.name = v.name && n.defined = v.defined
        && n.loc.source_name = path in
      let occurrences = List.concat_map (fun u -> List.filter same (Lazy.force u.nodes)) hover in
      let definition =
        match v.defined with
        | Some d when is_variable v -> [ Binder_of_variable d ]
        | Some d when d.source_name = path -> [ Definition_of_constant d ]
        | _ -> [] in
      definition
      @ List.map (fun (n : Compile.node) -> Occurrence n.loc)
          (List.sort_uniq (fun (a : Compile.node) b -> compare a.loc.source_start b.loc.source_start) occurrences)

(* --- semantic tokens ----------------------------------------------------------- *)

type token_type =
  | Function | EnumMember | Parameter | Variable | Keyword | Number | String
  | Type | TypeParameter | Macro

let token_type_name = function
  | Function -> "function" | EnumMember -> "enumMember" | Parameter -> "parameter"
  | Variable -> "variable" | Keyword -> "keyword" | Number -> "number" | String -> "string"
  | Type -> "type" | TypeParameter -> "typeParameter" | Macro -> "macro"

(* the code of a type in the protocol: its index in the legend *)
let token_code = function
  | Function -> 0 | EnumMember -> 1 | Parameter -> 2 | Variable -> 3 | Keyword -> 4
  | Number -> 5 | String -> 6 | Type -> 7 | TypeParameter -> 8 | Macro -> 9

(* The legend sent to the client *)
let token_types =
  [ Function; EnumMember; Parameter; Variable; Keyword; Number; String; Type; TypeParameter; Macro ]
  |> List.sort (fun a b -> compare (token_code a) (token_code b))
  |> List.map token_type_name
let token_modifiers = [ "declaration" ]

(* The type of the token of a symbol, if it has one: the predicates and
   functions that a rule defines are functions, the data constants are enum
   members, bound variables are parameters, the variables of a rule are
   variables. The nodes that cover
   more than a word (the type of a declaration) are not tokens. *)
let token_type (n : Compile.node) =
  match n.kind with
  | Compile.Constant (Predicate, _) | Constant (Function, _) ->
      (* only the symbol that a rule defines: in the body of the rules they are
         too many *)
      if n.declaration then Some Function else None
  | Constant (Data, _) -> Some EnumMember
  | Bound | Binder -> Some Parameter
  | Unification_variable -> Some Variable
  | Keyword -> Some Keyword
  | Literal (`Int | `Float) -> Some Number
  | Literal `String -> Some String
  | Literal `Other | Discard | Type_keyword -> None
  | Macro -> Some Macro
  | Type_constructor | Type_abbreviation -> Some Type
  | Type_variable -> Some TypeParameter

(* The tokens of the document, as the data of the protocol: for each one, the
   line and the column (UTF-16 units) relative to the previous one, the length,
   the type and the modifiers. Tokens that overlap or span lines are dropped. *)
let semantic_tokens ~path (text : Text.t) (hover : hover) =
  let tokens =
    List.concat_map (fun u -> List.filter_map (fun (n : Compile.node) ->
        if n.loc.source_name <> path then None
        else Option.map (fun t -> n.loc.source_start, n.loc.source_stop, t, n.declaration) (token_type n))
        (Lazy.force u.nodes)) hover in
  let tokens = List.sort_uniq compare tokens in
  let data = ref [] and last_line = ref 0 and last_col = ref 0 and last_stop = ref (-1) in
  List.iter (fun (start, stop, t, declaration) ->
      let p1 = Text.position_of_offset text start and p2 = Text.position_of_offset text stop in
      if start >= !last_stop && stop > start && p1.Lsp.Types.Position.line = p2.Lsp.Types.Position.line then begin
        let line = p1.line and col = p1.character in
        let delta_col = if line = !last_line then col - !last_col else col in
        data := (if declaration then 1 else 0) :: token_code t :: (p2.character - col) :: delta_col :: (line - !last_line) :: !data;
        last_line := line; last_col := col; last_stop := stop
      end) tokens;
  Array.of_list (List.rev !data)
