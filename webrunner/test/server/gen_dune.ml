(* Prints dune.inc: one subdir per way of running the web build of the server
   (see dune). Edit the lists below, then regenerate with
   make tests-webrunner PROMOTE=true. *)

(* the scripts of lsp/test, in the order of lsp/test/dune *)
let scripts =
  [ "accbad"; "accmissing"; "good"; "syntax"; "typeerr"; "warn"; "binders"; "library"; "macros"; "libdef"; "doc";
    "acctype"; "lists"; "accchar"; "run"; "assemble"; "anomaly"; "accinc"; "accopen"; "accdirs"; "stubs"; "pkgs"; "proj"; "projtoml"; "badproj"; "quoteproj"; "spill"; "macrobind"; "warnproj"; "projprefix"; "tomledit"; "accwarn" ]

(* accinc needs the server to be given -I, the web server has no command line;
   the files of accdirs, proj, badproj, quoteproj and warnproj are in subdirectories of
   lsp/test, which are not copied; the web server has no packages (pkgs) *)
let node_skip = [ "accinc"; "accdirs"; "pkgs"; "proj"; "projtoml"; "badproj"; "quoteproj"; "warnproj"; "projprefix"; "tomledit" ]

(* in a browser there are no files: the scripts that accumulate files *)
let browser_skip = [ "accbad"; "accchar"; "accdirs"; "accinc"; "acctype"; "good"; "library"; "pkgs"; "proj"; "projtoml"; "badproj"; "quoteproj"; "warnproj"; "projprefix"; "tomledit"; "accwarn"; "run" ]

let browser_scenarios = [ "auto"; "no-wasm-features"; "wasm-fails"; "no-wasm-assets"; "wrong-mime"; "no-wasm-script" ]

let wasm_assets = "(glob_files ../../../web_lsp_driver.bc.wasm.assets/*.wasm)"

let outputs ~skip extra =
  String.concat " "
    (("test_lsp.output" :: List.filter_map (fun s ->
         if List.exists (String.equal s) skip then None else Some (s ^ ".output")) scripts)
     @ extra)

(* runs test_lsp, which skips the scripts [skip] *)
let run ~skip =
  let run = "(with-stdout-to test_lsp.output (run %{exe:../../../../lsp/test/test_lsp.exe} ./server.sh .))" in
  match skip with [] -> run | _ -> Printf.sprintf "(setenv TEST_LSP_SKIP %s %s)" (String.concat "," skip) run

let subdir ~name ~server ~skip ~extra_outputs ~deps ~check =
  let outputs = outputs ~skip extra_outputs in
  Printf.printf {|
(subdir %s
 (copy_files ../../../../lsp/test/*.elpi)
 (rule
  (targets server.sh)
  (action
   (progn
    (with-stdout-to server.sh
     (echo "#!/bin/sh\nd=\"$(dirname \"$0\")\"\nexec node \"$d/../bridge.mjs\" %s\n"))
    (run chmod +x server.sh))))
 (rule
  (targets %s)
  (deps (glob_files *.elpi) server.sh ../bridge.mjs %s)
  (action
   %s))
 (rule
  (alias runtest-webrunner)
  (deps ../compare.cjs %s (glob_files ../*.expected) (glob_files ../../../../lsp/test/*.expected))
  (action %s)))
|}
    name server outputs deps (run ~skip) outputs check

let compare = "(run node ../compare.cjs . .. ../../../../lsp/test)"

let () =
  print_string "; generated by gen_dune.ml, do not edit\n";
  subdir ~name:"node-js" ~server:{|node \"$d/../../../web_lsp_driver.bc.js\"|} ~skip:node_skip ~extra_outputs:[]
    ~deps:"../node-worker.cjs ../../../web_lsp_driver.bc.js" ~check:compare;
  subdir ~name:"node-wasm" ~server:{|node \"$d/../../../web_lsp_driver.bc.wasm.js\"|} ~skip:node_skip
    ~extra_outputs:[] ~deps:("../node-worker.cjs ../../../web_lsp_driver.bc.wasm.js " ^ wasm_assets) ~check:compare;
  List.iter (fun scenario ->
      subdir ~name:("browser-" ^ scenario)
        ~server:(Printf.sprintf {|browser \"$d/../../../elpi-lsp-web.js\" %s \"$d/loaded.log\"|} scenario)
        ~skip:browser_skip ~extra_outputs:[ "loaded.log" ]
        ~deps:("../worker.cjs ../browser.cjs ../../../elpi-lsp-web.js ../../../web_lsp_driver.bc.js \
                ../../../web_lsp_driver.bc.wasm.js " ^ wasm_assets)
        ~check:(Printf.sprintf "(progn %s (diff ../loaded-%s.expected loaded.log))" compare scenario))
    browser_scenarios
